import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Set plot style
sns.set_style('whitegrid')
plt.rcParams['figure.figsize'] = (10, 6)

# Load the dataset
# IMPORTANT: You may need to change 'car_prices.csv' to the actual name of your data file.
try:
    df = pd.read_csv('car_prices.csv')
except FileNotFoundError:
    print("Error: 'car_prices.csv' not found. Please upload your dataset or update the file path.")
    print("Attempting to load a common alternative name: 'car_data.csv'")
    try:
        df = pd.read_csv('car_data.csv')
    except FileNotFoundError:
        print("Error: 'car_data.csv' also not found. Please ensure your dataset is correctly named and located.")
        df = None # Set df to None to prevent further errors

if df is not None:
    print("Dataset loaded successfully. Displaying the first 5 rows:")
    display(df.head())

"""### 1. Dataset Overview and Information"""

if df is not None:
    print("\nDataFrame Information:")
    display(df.info())

if df is not None:
    print("\nDescriptive Statistics for Numerical Features:")
    display(df.describe())

"""### 2. Missing Values Analysis"""

if df is not None:
    print("\nMissing Values:")
    missing_values = df.isnull().sum()
    missing_values = missing_values[missing_values > 0].sort_values(ascending=False)
    if missing_values.empty:
        print("No missing values found.")
    else:
        display(missing_values)

"""### 3. Univariate Analysis (Distribution of Features)"""

if df is not None:
    print("\nHistograms for Numerical Features:")
    numerical_cols = df.select_dtypes(include=['number']).columns
    for col in numerical_cols:
        plt.figure()
        sns.histplot(df[col].dropna(), kde=True)
        plt.title(f'Distribution of {col}')
        plt.xlabel(col)
        plt.ylabel('Frequency')
        plt.show()

if df is not None:
    print("\nValue Counts for Categorical Features (Top 10):")
    categorical_cols = df.select_dtypes(include=['object', 'category']).columns
    for col in categorical_cols:
        print(f"\n-- {col} --")
        display(df[col].value_counts().head(10))

"""### 4. Bivariate Analysis (Relationships between Features)"""

if df is not None and 'price' in df.columns.str.lower(): # Assuming 'price' is the target variable
    print("\nCorrelation Matrix:")
    correlation_matrix = df.select_dtypes(include=['number']).corr()
    plt.figure(figsize=(12, 10))
    sns.heatmap(correlation_matrix, annot=True, cmap='coolwarm', fmt=".2f")
    plt.title('Correlation Matrix of Numerical Features')
    plt.show()

if df is not None and 'price' in df.columns.str.lower():
    print("\nScatter Plots of Price vs. Key Numerical Features:")
    target_col = df.columns[df.columns.str.lower() == 'price'][0] # Get exact case of 'price'

    # Select a few highly correlated numerical features (if available) or common ones
    numeric_features = df.select_dtypes(include=['number']).columns.drop(target_col, errors='ignore')

    # Plot against top 3 correlated features if available, otherwise just some numericals
    if not numeric_features.empty:
        # Sort by correlation with target_col (absolute value)
        correlations = df[numeric_features].corrwith(df[target_col]).abs().sort_values(ascending=False)
        features_to_plot = correlations.head(3).index.tolist()

        for feature in features_to_plot:
            plt.figure()
            sns.scatterplot(x=df[feature], y=df[target_col])
            plt.title(f'{target_col} vs. {feature}')
            plt.xlabel(feature)
            plt.ylabel(target_col)
            plt.show()
    else:
        print("No other numerical features to plot against price.")

if df is not None and 'price' in df.columns.str.lower():
    print("\nBox Plots of Price vs. Key Categorical Features:")
    target_col = df.columns[df.columns.str.lower() == 'price'][0]
    categorical_cols = df.select_dtypes(include=['object', 'category']).columns

    # Plot against up to 3 categorical features with a reasonable number of unique values
    for col in categorical_cols:
        if df[col].nunique() < 10: # Limit to categories with fewer than 10 unique values for readability
            plt.figure(figsize=(12, 6))
            sns.boxplot(x=df[col], y=df[target_col])
            plt.title(f'{target_col} vs. {col}')
            plt.xlabel(col)
            plt.ylabel(target_col)
            plt.xticks(rotation=45, ha='right')
            plt.tight_layout()
            plt.show()
        else:
            print(f"Skipping box plot for '{col}' due to too many unique categories ({df[col].nunique()}).")

"""### Generating Synthetic Data to Demonstrate EDA"""

import numpy as np

print("Generating a synthetic car prices dataset...")

# Number of samples
n_samples = 1000

# Define features
np.random.seed(42)
make = np.random.choice(['Toyota', 'Honda', 'Ford', 'BMW', 'Mercedes'], n_samples)
model_year = np.random.randint(2000, 2024, n_samples)
mileage = np.random.randint(1000, 200000, n_samples)
engine_size = np.random.uniform(1.0, 5.0, n_samples).round(1)
fuel_type = np.random.choice(['Petrol', 'Diesel', 'Electric', 'Hybrid'], n_samples, p=[0.6, 0.2, 0.1, 0.1])
transmission = np.random.choice(['Automatic', 'Manual'], n_samples, p=[0.7, 0.3])
owner_type = np.random.choice(['First', 'Second', 'Third'], n_samples, p=[0.5, 0.3, 0.2])
seats = np.random.choice([4, 5, 7], n_samples, p=[0.1, 0.8, 0.1])

# Generate price based on some features (simplified logic)
price = (50000 - (2023 - model_year) * 2000  # Newer cars are more expensive
         - mileage * 0.1 # Higher mileage reduces price
         + engine_size * 3000 # Larger engine size increases price
         + (np.random.rand(n_samples) - 0.5) * 10000) # Random noise

# Adjust price based on make (e.g., BMW/Mercedes are more expensive)
price[make == 'BMW'] += 15000
price[make == 'Mercedes'] += 18000
price[make == 'Toyota'] -= 5000

# Adjust price based on fuel type
price[fuel_type == 'Electric'] += 10000
price[fuel_type == 'Hybrid'] += 5000

price[transmission == 'Manual'] -= 2000

# Ensure prices are positive
price = np.maximum(1000, price).round(-2)

df = pd.DataFrame({
    'Make': make,
    'Model_Year': model_year,
    'Mileage': mileage,
    'Engine_Size': engine_size,
    'Fuel_Type': fuel_type,
    'Transmission': transmission,
    'Owner_Type': owner_type,
    'Seats': seats,
    'Price': price
})

print("Synthetic dataset created successfully. Displaying the first 5 rows:")
display(df.head())

